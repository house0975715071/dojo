export function buildPrompt(role, levelKey) {
  const lv = LEVELS[levelKey] || LEVELS.normal;
  return [
    '我是台灣的房仲新人，想跟你做「角色扮演對練」。請你完全照下面的設定演，不要跳出角色。',
    '',
    `【你扮演】${role.title}`,
    `【人設】${role.who}`,
    `【你心裡的祕密（不要直接說出來，要我問對問題、建立信任才慢慢透露）】${role.hidden}`,
    `【難度：${lv.name}】${lv.rule}`,
    `【我的目標】${role.goal}`,
    '',
    '【規則】',
    '1. 一次只講一段話（1～3 句），然後停下來等我回。',
    '2. 依我的回應調整態度：我有同理心、問對問題、拿數據說話，你就慢慢放軟；我推銷、講罐頭話、保證東保證西，你就變冷淡。',
    '3. 不要教我、不要給提示，你就是客人。',
    '4. 用繁體中文、台灣口語。稱呼用大哥、大姐、先生、小姐，不用姓氏。',
    '5. 如果我講了違反法規或職業道德的話（例如：收斡旋金沒提要約書、保證貸款成數或增值、捏造別的買方、洩漏另一方底價、叫你在空白委託書簽名、倒填委託日期、貶低同業），照客人的真實反應演，結束時一定要點出來。',
    '6. 我打「結束」時，跳出角色，用這個格式評分：',
    '   - 成交機率：__%',
    '   - 信任度：__／100',
    '   - 法遵：有沒有踩到紅線（列出哪一句、違反什麼）',
    '   - 做得好的 3 點',
    '   - 要改的 3 點（每點附上「下次可以這樣說」的示範句）',
    '   - 一句要背起來的話術',
    '',
    `【開場】請你先講第一句：${role.open}`,
  ].join('\n');
}
